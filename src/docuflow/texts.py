def field_prompt(index: int, total: int, label: str, example: str) -> str:
    """Запрос значения поля: какой это шаг, что за поле и пример заполнения."""
    return f"📝 Поле {index}/{total}: {label}\nПример: {example}"


def field_invalid(error: str) -> str:
    """Отказ валидации: что именно не так с введённым значением."""
    return f"⚠️ {error}. Попробуйте ещё раз:"


def confirm_summary(summary: str) -> str:
    """Шаг подтверждения: сводка введённых значений перед генерацией."""
    return f"📋 Проверьте данные:\n{summary}"


def document_line(doc_id: object, name: str, created_at: str) -> str:
    """Строка списка документов: id, шаблон и дата создания."""
    return f"📄 #{doc_id} — {name} ({created_at})"


def admin_stats(templates: int, documents: int, users: int) -> str:
    """Статистика администратора: шаблоны, документы, пользователи."""
    return f"📊 Статистика:\n  Шаблонов: {templates}\n  Документов: {documents}\n  Пользователей: {users}"


def free_limit(limit: object) -> str:
    """Бесплатный лимит генераций в месяц."""
    return f"💳 Бесплатный лимит: {limit} документов/мес"
